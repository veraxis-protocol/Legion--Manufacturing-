STAGES = [
    ("01_rfq", "tests/runtime/inputs/e2e/rfq_rebot_email.txt", "input (synthetic, labelled)"),
    ("02_intake", "evidence/SKILL_OUTPUTS/E01/positive/run.json", "Claude: customer-inquiry-intake"),
    ("03_bom_engineering", "evidence/E2E/02_engineering.json", "LEGION: real STEP -> XCAF BOM -> ZTL review"),
    ("03b_bom_handoff", "evidence/E2E/02_bom_handoff.json", "LEGION -> Claude handoff"),
    ("04_cost", "evidence/SKILL_OUTPUTS/E02/positive/run.json", "Claude: quote-build"),
    ("05_supplier", "evidence/SKILL_OUTPUTS/E03/positive/run.json", "Claude: supplier-quote-request + comparison"),
    ("06_coalition", "evidence/E2E/06_commercial.json", "LEGION: Deal-Rescue coalition rule -> proposal contract"),
]


def _outputs_text(run: dict, case: str) -> str:
    base = ROOT / "evidence" / "SKILL_OUTPUTS" / case / "positive" / "out"
    return "\n".join((base / o["path"]).read_text(encoding="utf-8", errors="replace") for o in run.get("outputs", [])
                     if o.get("text"))


def assemble() -> dict:
    trace, missing = [], []
    for sid, rel, what in STAGES:
        p = ROOT / rel
        if not p.exists():
            missing.append(sid)
            trace.append({"stage": sid, "what": what, "artifact": rel, "status": "NOT RUN"})
            continue
        d = json.loads(p.read_text(encoding="utf-8")) if p.suffix == ".json" else None
        st = (d or {}).get("status") or ("PASS" if p.suffix != ".json" else "PRESENT")
        trace.append({"stage": sid, "what": what, "artifact": rel, "sha256": sha(p), "status": st,
                      "runtime": (d or {}).get("runtime", {}).get("model") if d else None})
    checks = []
    if not missing:
        e01 = json.loads((ROOT / STAGES[1][1]).read_text(encoding="utf-8"))
        e02 = json.loads((ROOT / STAGES[4][1]).read_text(encoding="utf-8"))
        e03 = json.loads((ROOT / STAGES[5][1]).read_text(encoding="utf-8"))
        eng = json.loads((E2E / "02_engineering.json").read_text(encoding="utf-8"))
        com = json.loads((E2E / "06_commercial.json").read_text(encoding="utf-8"))
        hand = json.loads((E2E / "02_bom_handoff.json").read_text(encoding="utf-8"))
        intake_txt, cost_txt, sup_txt = _outputs_text(e01, "E01"), _outputs_text(e02, "E02"), _outputs_text(e03, "E03")
        staged_e02 = [i["path"] for i in e02["inputs"]]
        staged_e03 = [i["path"] for i in e03["inputs"]]
        checks += [
            {"check": "intake names the 20-set quantity and the reBot STEP", "pass": bool(re.search(r"\b20\b", intake_txt))
             and "reBot" in intake_txt},
            {"check": "intake records tolerances as missing (customer says 'whatever the design needs')",
             "pass": bool(re.search(r"toleranc[^\n]{0,120}(missing|not (?:stated|specified|provided)|unknown|TBD|open)",
                                    intake_txt, re.I))},
            {"check": "BOM extraction from the real STEP is T (40/40 positions)", "pass": eng["bom"]["status"] == T},
            {"check": "engineering verdict for the real reBot stays Z (missing sourced requirements)",
             "pass": eng["verification"]["engineering_verdict"] == Z},
            {"check": "controlled ZTL cases: positive T, negative F (real MCP -> stand -> checker)",
             "pass": [c["verdict"] for c in eng["controlled_cases"]] == [T, F]},
            {"check": "cost stage consumed the intake output and the BOM handoff (exact files staged)",
             "pass": any("02_bom_handoff.json" in x for x in staged_e02) and any(x.startswith("inputs/intake/") for x in staged_e02)},
            {"check": "quote prices material from a named PO and does not state a tolerance for the parts",
             "pass": bool(re.search(r"PO-307\d\d", cost_txt))},
            {"check": "quote carries the Z engineering status / missing requirements forward",
             "pass": bool(re.search(r"\bZ\b|not (?:engineering[- ])?verified|engineering[^\n]{0,60}(?:open|missing|pending)", cost_txt, re.I))},
            {"check": "supplier stage consumed the BOM handoff and both supplied test quotes",
             "pass": sum("rail_bid_" in x for x in staged_e03) == 2},
            {"check": "supplier comparison flags Y's unstated accuracy class and MOQ 250 vs need",
             "pass": bool(re.search(r"accuracy", sup_txt, re.I)) and "250" in sup_txt},
            {"check": "coalition: 5 x 20 = 100 meets MOQ 100 (demonstration only)",
             "pass": com["moq_rule"]["meets_moq"] and com["moq_rule"]["units"] == 100 and com["moq_rule"]["buyers"] == 5},
            {"check": "simulated buyers are never treated as real (as-if-real -> Z)",
             "pass": com["participation"]["as_if_real_result"] == Z and com["participation"]["real_third_party_buyers"] == 0},
            {"check": "duplicate buyer is rejected", "pass": any(x.get("why") == "duplicate_buyer_or_request"
                                                                 for x in com["scenarios"]["duplicate_buyer"]["excluded"])},
            {"check": "4 x 20 = 80 does not meet MOQ 100", "pass": com["scenarios"]["short_of_moq"]["decision"]["verdict"] != T
             or com["scenarios"]["short_of_moq"]["decision"].get("route") != "COALITION"},
            {"check": "proposal not admitted, no external effects", "pass": com["coalition_proposal"]["external_effects"] == 0
             and com["coalition_proposal"]["reliance"] == "NOT_ADMITTED_TO_EXISTING_FEDERATION"},
            {"check": "every Claude stage independently evaluated PASS",
             "pass": all(json.loads((ROOT / STAGES[i][1]).read_text(encoding="utf-8"))["status"] == "PASS" for i in (1, 4, 5))},
            {"check": "BOM handoff matches the engineering artifact (no re-derivation)",
             "pass": hand["bom_status"] == eng["bom"]["status"] and len(hand["cnc_parts"]) == sum(p["group"] == "cnc" for p in eng["parts"])},
        ]
    ok = not missing and all(c["pass"] for c in checks)
    doc = {"schema": "legion.manufacturing.e2e-trace.v1", "inquiry_ref": INQUIRY, "trace": trace, "handoff_checks": checks,
           "missing_stages": missing, "marketplace": "BLOCKED (license; see 06_commercial.json)",
           "status": "PASS" if ok else ("NOT RUN" if missing else "FAIL"),
           "scope": "PASS means the workflow ran end to end with real Claude stages, the real STEP/ZTL route and the "
                    "existing coalition rule; buyers and supplier quotes are synthetic and labelled; the real reBot "
                    "engineering verdict is Z; Marketplace/Federation admission is BLOCKED."}
    p = ROOT / "evidence" / "MANUFACTURING_E2E.json"
    p.write_text(json.dumps(doc, indent=1, ensure_ascii=False) + "\n", encoding="utf-8", newline="\n")
    print(json.dumps({"status": doc["status"], "failed": [c["check"] for c in checks if not c["pass"]], "missing": missing}))
    return doc


