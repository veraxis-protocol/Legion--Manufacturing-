"""WO-LMFG-004 G: the integrated manufacturing workflow, one continuous trace.

  RFQ (synthetic, labelled) -> customer-inquiry-intake (Claude, original skill)
     -> drawing/BOM extraction: the REAL reBot B601 STEP through OpenCascade XCAF (Deal-Rescue cad_xcaf / cad027_review)
     -> ZTL engineering review: the real ZTL Engineer MCP -> ZTL Stand -> checker (legion/engineering/ztl_adapter.py)
     -> manufacturing cost estimate (Claude, quote-build, on the intake + the extracted BOM + labelled cost files)
     -> supplier quote request + comparison (Claude, supplier-quote-request, on explicitly SUPPLIED TEST quotes)
     -> coalition: Deal-Rescue industrial/core.py group_demand / evaluate_quote / choose_route / verify_ztl_binding
     -> coalition proposal input contract (legion.industrial.federation-proposal.v1 shape from core.run_case)
     -> LEGION Marketplace / Federation admission: BLOCKED (PolyForm-NC source, no commercial authorisation)

Stages (each writes evidence/E2E/<n>_<stage>.json; nothing is regenerated by a later stage):
  engineering   needs OpenCascade (run in WSL / Linux CI): BOM + requirements + ZTL review, and the BOM handoff file
  commercial    stdlib only: MOQ coalition (5 x 20 = 100) and route comparison, synthetic vs real participation
  assemble      the trace: every artifact's SHA-256, and the handoff checks between stages
The Claude stages are the skill cases E01..E03 in tests/runtime/cases.json (tools/skill_run.py).
"""
from __future__ import annotations

import argparse
import hashlib
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))
E2E = ROOT / "evidence" / "E2E"
INQUIRY = "RFQ-E2E-REBOT-001"
SITE = "EPW1"
T, F, Z = "T", "F", "Z"


def sha(p: Path) -> str:
    return hashlib.sha256(p.read_bytes()).hexdigest()


def write(name: str, doc: dict) -> Path:
    E2E.mkdir(parents=True, exist_ok=True)
    p = E2E / name
    p.write_text(json.dumps(doc, indent=1, ensure_ascii=False, default=str) + "\n", encoding="utf-8", newline="\n")
    return p


# ------------------------------------------------------------------ stage: engineering (real STEP, real ZTL)
def engineering() -> dict:
    from legion.engineering import pinned_source as P
    from legion.engineering import step_intake as S
    from legion.engineering import ztl_adapter as A
    import OCP  # noqa: F401  (the real CAD route; an ImportError is an error, never a skip)
    import importlib.util
    P.materialize()                     # pinned Deal-Rescue copy, every file verified before use
    P.import_path()
    files = P.fetch_reference_cad()
    pin = P.load_pin()
    rt = A.runtime()
    out = S.step_intake(files["step"]["path"], files["readme"]["path"], pin["reference_cad"]["files"]["step"]["sha256"],
                        SITE, INQUIRY, verifier=rt)
    from deal_rescue.industrial import cad_xcaf
    xcaf = cad_xcaf.read_assembly(Path(files["step"]["path"]), pin["reference_cad"]["files"]["step"]["sha256"])
    readme = Path(files["readme"]["path"]).read_text(encoding="utf-8")
    spec = importlib.util.spec_from_file_location("dr_test_cad027_demo", P.DEPS / "tests" / "test_cad027_demo.py")
    demo = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(demo)
    tol, tol_src = demo.TEST_ONLY_TOL[0], demo.TEST_ONLY_TOL[1] + " (Deal-Rescue tests/test_cad027_demo.py @6d5563a)"
    controlled = A.controlled_rail_cases(xcaf, readme, hashlib.sha256(readme.encode("utf-8")).hexdigest(), rt, tol,
                                         tol_src)
    ver = out["stages"].get("verification", {})
    eng = {"stage": "engineering", "inquiry_ref": INQUIRY,
           "source": {"repository": pin["reference_cad"]["repository"], "commit": pin["reference_cad"]["commit"],
                      "step": {k: files["step"].get(k) for k in ("path", "sha256", "bytes") if k != "path"} |
                              {"file": Path(files["step"]["path"]).name},
                      "readme_sha256": sha(Path(files["readme"]["path"])), "license": pin["reference_cad"]["license"]},
           "intake": out["stages"]["intake"], "bom": out["stages"]["bom"],
           "requirements": {k: v for k, v in out["stages"]["requirements"].items() if k != "parts"},
           "parts": out["stages"]["requirements"]["parts"],
           "verification": {"engineering_verdict": out["engineering_verdict"],
                            "predicates": [{k: p.get(k) for k in ("predicate_id", "part_id", "verdict", "reason",
                                                                  "stand_verdict", "proof_id", "missing")}
                                           for p in ver.get("predicates", [])],
                            "aggregate": ver.get("verdict"), "missing_for_engineering_T": ver.get("missing_for_engineering_T")},
           "controlled_cases": [{k: c.get(k) for k in ("predicate_id", "verdict", "reason", "stand_verdict", "proof_id",
                                                       "deliberate_change", "admissible_for_rebot", "binding")}
                                for c in controlled],
           "geometry_estimates": len(out.get("geometry_estimates", [])),
           "revision_evidence": out.get("revision_evidence")}
    write("02_engineering.json", eng)
    # handoff for the Claude cost stage: only what the extraction and the readme state, with their sources
    cnc = [{"part_id": p["part_id"], "quantity_per_arm": p["quantity"], "material": p["material"],
            "material_source": p["material_source"], "process": p["process"], "tolerance": p["tolerance"],
            "tolerance_source": p["tolerance_source"], "missing_requirements": p["missing_requirements"],
            "geometry_from_step": p["geometry_observed"]} for p in eng["parts"] if p["group"] == "cnc"]
    handoff = {"about": "BOM handoff from the LEGION engineering stage (real reBot B601 STEP via OpenCascade XCAF, "
                        "readme-reconciled). Geometry is from the STEP; material/process/quantity from the project "
                        "readme lines cited. No tolerance, finish or inspection requirement is invented.",
               "source": eng["source"], "bom_status": eng["bom"]["status"],
               "engineering_verdict": eng["verification"]["engineering_verdict"],
               "engineering_missing": eng["verification"]["missing_for_engineering_T"],
               "cnc_parts": cnc,
               "purchased_rail": {"name": "Linear rail", "model": "MGN9-170mm", "quantity_per_arm": 1,
                                  "source": "readme purchased-parts table (Deal-Rescue cad027_review.parse_readme)"}}
    write("02_bom_handoff.json", handoff)
    print(json.dumps({"bom": eng["bom"]["status"], "engineering_verdict": eng["verification"]["engineering_verdict"],
                      "controlled": [c["verdict"] for c in controlled], "cnc_parts": len(cnc)}))
    return eng


